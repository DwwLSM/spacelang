#!/usr/bin/env python3
"""Compile a .sp program into a standalone executable.

    python native/embed.py bootstrap/demos/fib.sp [-o fib.exe] [--no-static]

The result contains the native VM and the program bytes: running it executes
the program directly, with no Python and no .sp file next to it.  This is the
"ahead-of-time" path -- the program and its runtime are one binary -- as opposed
to `spvm.exe program.sp`, where the program stays a separate file.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
VM_SOURCE = HERE / "spvm.cpp"

TEMPLATE = """// Generated by native/embed.py -- do not edit.
#define SPVM_NO_MAIN
#include "spvm.cpp"

namespace {{
const unsigned char kProgram[] = {{
{array}
}};
}}  // namespace

int main() {{
    const std::string text(reinterpret_cast<const char*>(kProgram), sizeof(kProgram));
    return spvm_run_text(text, "{name}", {{}});
}}
"""


def format_bytes(data: bytes, per_line: int = 20) -> str:
    lines = []
    for start in range(0, len(data), per_line):
        chunk = data[start:start + per_line]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Embed a .sp program into a standalone executable.")
    parser.add_argument("program", type=Path)
    parser.add_argument("-o", "--output", type=Path)
    parser.add_argument("--no-static", action="store_true", help="link the C++ runtime dynamically")
    parser.add_argument("--compiler", default="g++")
    args = parser.parse_args(argv)

    if not args.program.is_file():
        print(f"error: {args.program} not found", file=sys.stderr)
        return 1
    compiler = shutil.which(args.compiler)
    if compiler is None:
        print(f"error: '{args.compiler}' not found on PATH", file=sys.stderr)
        return 1

    data = args.program.read_bytes()
    output = (args.output or args.program.with_suffix(".exe")).resolve()
    generated = output.parent / (output.stem + ".embed.cpp")
    generated.write_text(
        TEMPLATE.format(array=format_bytes(data), name=args.program.name),
        encoding="utf-8",
    )

    command = [
        compiler,
        "-O2",
        "-std=c++17",
        f"-I{HERE}",
        "-o",
        str(output),
        str(generated),
    ]
    if not args.no_static:
        command.insert(1, "-static")
    subprocess.run(command, check=True)

    print(f"{args.program} ({len(data):,} bytes) -> {output} ({output.stat().st_size:,} bytes)")
    print(f"  generated source: {generated}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
